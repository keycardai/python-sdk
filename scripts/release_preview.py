#!/usr/bin/env python3
"""
Render what a PR releases: one line per package that gets a version bump,
followed by only the changelog entries this PR adds.

Each package's answer comes from `cz bump --dry-run`, which prints the bump
line, the increment, and the changelog section the bump would write, so the
preview never repeats a package's history. Packages with nothing to release
are summarized in one line; commitizen's warnings never reach the output.

Usage:
  python scripts/release_preview.py [--max-chars N] [--summary-url URL]

The same renderer feeds the PR comment (scripts/pr_comment.py, capped) and
the job summary (uncapped).
"""

import argparse
import os
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from changelog import discover_workspace_packages  # noqa: E402

# commitizen exit codes for "nothing to release" (commitizen/exceptions.py).
NO_COMMITS_FOUND = 3
NO_COMMITS_TO_BUMP = 21

# Lines commitizen writes to stderr on every run in this monorepo. They are
# warnings, not failures, and they never belong in a preview.
IGNORED_STDERR_PREFIXES = (
    "Multiple config files detected",
    "Invalid version tag:",
)

HEADER = "## Release preview"
SIGNATURE = "This comment was automatically generated by the release preview workflow"
NOTHING_LINE = "This PR releases nothing."
NO_OTHERS_LINE = "No other package releases."
TRUNCATED_LINE = "Preview cut at {max_chars} characters; the full preview is in the job summary{suffix}."


@dataclass
class PackageRelease:
    name: str
    current_version: str
    next_version: str
    increment: str
    entries: list[str] = field(default_factory=list)


@dataclass
class PreviewError:
    name: str
    message: str


@dataclass
class Preview:
    releases: list[PackageRelease] = field(default_factory=list)
    skipped: list[str] = field(default_factory=list)
    errors: list[PreviewError] = field(default_factory=list)


def run_command(cmd: list[str], cwd: str | None = None) -> tuple[int, str, str]:
    result = subprocess.run(cmd, capture_output=True, text=True, cwd=cwd)
    return result.returncode, result.stdout, result.stderr


def filter_stderr(stderr: str) -> str:
    """Drop commitizen's known warnings, keep anything that explains a failure."""
    kept = [
        line
        for line in stderr.splitlines()
        if line.strip() and not line.strip().startswith(IGNORED_STDERR_PREFIXES)
    ]
    return "\n".join(kept)


def parse_bump_dry_run(
    name: str, exit_code: int, stdout: str, stderr: str
) -> PackageRelease | PreviewError | None:
    """Turn one `cz bump --dry-run` run into a release, nothing, or an error.

    Returns None when commitizen reports nothing to release (exit 3 or 21).
    """
    if exit_code in (NO_COMMITS_FOUND, NO_COMMITS_TO_BUMP):
        return None
    if exit_code != 0:
        detail = filter_stderr(stderr) or stdout.strip() or f"exit code {exit_code}"
        return PreviewError(name, detail.splitlines()[-1])

    current = next_version = increment = None
    entries: list[str] = []
    in_changelog = False
    for raw in stdout.splitlines():
        line = raw.strip()
        if line.startswith("bump:") and "→" in line:
            parts = line.split()
            arrow = parts.index("→")
            current, next_version = parts[arrow - 1], parts[arrow + 1]
        elif line.startswith("increment detected:"):
            increment = line.split(":", 1)[1].strip().lower()
        elif line.startswith("## "):
            in_changelog = True
        elif in_changelog and line:
            entries.append(line)

    if not (current and next_version):
        return PreviewError(name, "could not read the bump line from commitizen")
    return PackageRelease(name, current, next_version, increment or "?", entries)


def collect_preview(packages: list[dict] | None = None) -> Preview:
    """Run `cz bump --dry-run` in every workspace package."""
    preview = Preview()
    for package in packages or discover_workspace_packages():
        name = package["package_name"]
        # --yes answers cz's first-tag prompt for packages with no tag yet.
        exit_code, stdout, stderr = run_command(
            ["uv", "run", "cz", "bump", "--dry-run", "--yes"], cwd=package["package_dir"]
        )
        outcome = parse_bump_dry_run(name, exit_code, stdout, stderr)
        if outcome is None:
            preview.skipped.append(name)
        elif isinstance(outcome, PreviewError):
            preview.errors.append(outcome)
        else:
            preview.releases.append(outcome)
    return preview


def render_preview(preview: Preview) -> str:
    lines = [HEADER, ""]
    if not preview.releases:
        lines.append(NOTHING_LINE)
    for release in preview.releases:
        lines.append(
            f"**{release.name}** {release.current_version} → {release.next_version} ({release.increment})"
        )
        lines.append("")
        lines.extend(release.entries or ["(no changelog entries)"])
        lines.append("")
    if preview.releases and preview.skipped:
        lines.append(NO_OTHERS_LINE)
        lines.append("")
    for error in preview.errors:
        lines.append(f"**{error.name}**: could not compute a preview ({error.message})")
    while lines and not lines[-1]:
        lines.pop()
    return "\n".join(lines)


def cap_text(text: str, max_chars: int, summary_url: str | None = None) -> str:
    """Cut text to max_chars, with a closing line that says where the rest is."""
    if len(text) <= max_chars:
        return text
    suffix = f" ({summary_url})" if summary_url else ""
    closing = "\n\n" + TRUNCATED_LINE.format(max_chars=max_chars, suffix=suffix)
    cut = text[: max_chars - len(closing)]
    cut = cut[: cut.rfind("\n")] if "\n" in cut else cut
    return cut.rstrip() + closing


def job_summary_url() -> str | None:
    server = os.environ.get("GITHUB_SERVER_URL")
    repo = os.environ.get("GITHUB_REPOSITORY")
    run_id = os.environ.get("GITHUB_RUN_ID")
    if server and repo and run_id:
        return f"{server}/{repo}/actions/runs/{run_id}"
    return None


def main() -> None:
    parser = argparse.ArgumentParser(description="Render what this PR releases")
    parser.add_argument(
        "--max-chars", type=int, default=None, help="cap the output at this many characters"
    )
    args = parser.parse_args()
    text = render_preview(collect_preview())
    if args.max_chars:
        text = cap_text(text, args.max_chars, job_summary_url())
    print(text)


if __name__ == "__main__":
    main()
